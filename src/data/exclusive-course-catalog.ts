export type ProgramKind = "course" | "certification";

export type ProgramModule = {
  title: string;
  body: string;
};

export type ProgramDomain = {
  title: string;
  modules: ProgramModule[];
};

export type RelatedProgram = {
  title: string;
  href: string;
  desc: string;
};

export type ExclusiveProgram = {
  kind: ProgramKind;
  slug: string;
  href: string;
  number?: string;
  code: string;
  title: string;
  shortTitle: string;
  category: string;
  image: string;
  duration: string;
  pricePkr?: string;
  priceUsd?: string;
  oldPriceUsd?: string;
  summary: string;
  description: string;
  labTitle: string;
  labCommands: string[];
  audience: string[];
  domains: ProgramDomain[];
  tools: string[];
  outcomes: string[];
  projects: string[];
  includes: string[];
  related: RelatedProgram[];
};

type CourseSeed = Omit<ExclusiveProgram, "kind" | "href" | "audience" | "domains" | "includes" | "related"> & {
  focus: string[];
  relatedSlugs: string[];
};

type CertificationSeed = Omit<ExclusiveProgram, "kind" | "href" | "audience" | "domains" | "includes" | "related"> & {
  tracks: string[];
  relatedSlugs: string[];
};

