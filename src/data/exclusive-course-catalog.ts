function buildCourseDomains(focus: string[]): ProgramDomain[] {
  return focus.map((topic) => ({
    title: topic,
    modules: [
      {
        title: `${topic} fundamentals`,
        body: `Build the core mental model, vocabulary, workflow, and safety boundaries needed to use ${topic.toLowerCase()} professionally.`,
      },
      {
        title: `${topic} hands-on labs`,
        body: `Apply the concepts in guided exercises, realistic scenarios, tool practice, and instructor-reviewed assignments.`,
      },
      {
        title: `${topic} project delivery`,
        body: `Turn the skill into portfolio evidence through documentation, reporting, demos, and a practical final deliverable.`,
      },
    ],
  }));
}

function buildCertificationDomains(tracks: string[]): ProgramDomain[] {
  return tracks.map((track) => ({
    title: track,
    modules: [
      {
        title: `${track} skill validation`,
        body: "Review the required knowledge areas, labs, and professional evidence expected for this certification track.",
      },
      {
        title: `${track} capstone work`,
        body: "Complete scenario-based assignments that combine planning, implementation, testing, documentation, and presentation.",
      },
      {
        title: `${track} assessment`,
        body: "Defend your approach through practical review, technical questioning, and a verified final evaluation.",
      },
    ],
  }));
}

