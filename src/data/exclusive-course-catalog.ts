function relatedCourses(slugs: string[]): RelatedProgram[] {
  return slugs
    .map((slug) => courseSeeds.find((course) => course.slug === slug))
    .filter((course): course is CourseSeed => Boolean(course))
    .map((course) => ({
      title: course.title,
      href: `/courses/${course.slug}`,
      desc: course.summary,
    }));
}

